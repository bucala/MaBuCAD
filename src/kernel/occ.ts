import initOpenCascade from "replicad-opencascadejs/src/replicad_single.js";
import wasmUrl from "replicad-opencascadejs/src/replicad_single.wasm?url";
import { setOC } from "replicad";

let kernelPromise: Promise<void> | null = null;

/**
 * Boots the OpenCASCADE WebAssembly kernel and hands it to replicad.
 *
 * The wasm is about 11 MB, so loading is deferred until the first feature actually needs
 * geometry rather than paid on startup. The promise is cached, so concurrent rebuilds all
 * await the same initialisation instead of racing to start several.
 *
 * The application's content security policy permits `wasm-unsafe-eval`, which is what lets
 * the module compile at all, and `unsafe-eval`, which it needs for a second, less obvious
 * reason: Emscripten's embind builds its C++↔JS call invokers by *compiling a string* —
 * `craftInvokerFunction` and `emval_addMethodCaller` both end in `new_(Function, body)`
 * (see `replicad-opencascadejs/src/replicad_single.js`). Those invokers are crafted lazily,
 * per signature, the first time a given binding is actually called, so a CSP without
 * `unsafe-eval` does not fail at boot — it fails much later, on whichever operation happens
 * to be the first to need an uncrafted invoker. That is what used to break Circular Pattern
 * ("Evaluating a string as JavaScript violates the following Content Security Policy
 * directive…" surfacing as a feature error) and every Drawing view insertion, while extrudes
 * and fillets kept working. Tightening `script-src` back up reintroduces exactly that class
 * of bug; the eval'd code is generated by the kernel we ship ourselves, and `default-src`
 * plus `connect-src` still keep the webview from loading or reaching anything remote.
 */
export function initKernel(): Promise<void> {
  if (!kernelPromise) {
    kernelPromise = initOpenCascade({ locateFile: () => wasmUrl })
      .then((oc) => {
        setOC(oc as Parameters<typeof setOC>[0]);
      })
      .catch((error: unknown) => {
        // Clear the cache so a later attempt can retry rather than resolving a dead promise.
        kernelPromise = null;
        throw error;
      });
  }

  return kernelPromise;
}

/** Whether the kernel has finished booting, for reporting progress in the UI. */
export function isKernelStarted(): boolean {
  return kernelPromise !== null;
}
