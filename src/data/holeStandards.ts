/**
 * Fastener-standard hole data: clearance-hole shaft diameters and tapped-hole tap-drill
 * diameters, sourced from Autodesk's own Hole Wizard reference spreadsheets (the classic
 * "Clearance Hole Spreadsheet" and thread-data workbook shipped with Inventor) and reduced
 * to what `HoleWizard` actually needs — every distance already converted to millimetres
 * regardless of the standard's native unit, so nothing downstream has to think about units.
 *
 * This is deliberately a subset of what the source spreadsheets contain, not a transcription
 * of all of it:
 * - Clearance: all six standards the spreadsheet has (ISO, DIN, ANSI Metric M, ANSI Unified,
 *   JIS, GOST), each deduplicated to one row per nominal size — the source repeats the same
 *   shaft-clearance figures once per fastener head style (flat head, socket head, hex head,
 *   ...), and head geometry (counterbore/countersink dimensions) isn't modelled yet, so only
 *   the shaft clearance a style-independent hole needs is kept.
 * - Tapped: three of the thread-data workbook's ~30 sheets (ISO Metric, ANSI Metric M, ANSI
 *   Unified restricted to the UNC/UNF/UNEF series), narrowed to a practical fastener range
 *   (roughly M1-M100 / #0-2in) — the source also carries micrometre-scale instrument threads
 *   and metre-scale industrial ones neither this range nor a mechanical CAD part is likely to
 *   need. The other sheets (JIS/DIN/GOST/BSP taps, NPT and other pipe threads, Acme and
 *   trapezoidal threads, wood- and self-tapping screws, ...) are the same shape of table and
 *   can be added the same way if a future hole needs them.
 */

export type ClearanceStandardId = "iso" | "din" | "ansi-metric" | "ansi-unified" | "jis" | "gost";
export type ClearanceFit = "close" | "normal" | "loose";

export interface ClearanceSizeEntry {
  /** Nominal fastener size label, e.g. "M6" or "#8". */
  size: string;
  close: number;
  normal: number;
  loose: number;
}

export interface ClearanceStandard {
  id: ClearanceStandardId;
  label: string;
  sizes: ClearanceSizeEntry[];
}

export type TappedStandardId = "iso-metric" | "ansi-metric" | "ansi-unified";

export interface TappedSizeEntry {
  /** Full thread callout, e.g. "M6x1" or "1/4-20 UNC". */
  designation: string;
  /** Nominal size portion of the designation, e.g. "M6" or "1/4" — groups pitch variants
   * of the same nominal size together in the picker (a size has one coarse pitch and
   * usually one or more fine pitches, each its own row here). */
  sizeLabel: string;
  /** Major diameter in mm — same value for every pitch variant of one sizeLabel. */
  nominalSize: number;
  /** Thread pitch in mm for a metric standard, threads-per-inch for ANSI Unified. */
  pitch: number;
  /** Internal (nut/tapped-hole) thread class, e.g. "6H" or "2B". */
  internalClass: string;
  /** Recommended tap drill diameter in mm. */
  tapDrill: number;
}

export interface TappedStandard {
  id: TappedStandardId;
  label: string;
  /** "unified" designations sort/parse differently (fraction-and-TPI vs. M-and-pitch). */
  kind: "metric" | "unified";
  entries: TappedSizeEntry[];
}

