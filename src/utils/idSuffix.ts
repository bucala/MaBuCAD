/**
 * The highest numeric `-<n>` suffix among every string field found anywhere inside
 * `value`, scanned recursively — every id this app generates (`documentStore.ts`'s
 * `nextId`, `sketchModel.ts`'s `uid`, `templateStore.ts`'s `nextId`) has exactly this
 * `<prefix>-<n>` shape. Used to reseed a module's own id counter after loading persisted
 * state (Open, autosave restore, a tab switch, `templateStore`'s own localStorage
 * rehydration), so the very next freshly generated id can never collide with one already
 * present in what was just loaded — each counter's own seed function only ever raises it,
 * never lowers it, since a different document opened earlier in this same session may
 * already have pushed it higher than anything the newly loaded one contains.
 */
const ID_SUFFIX = /-(\d+)$/;
/** Real ids generated by this app are always short; skip long strings (an imported STEP
 * blob, a pasted note, base64 asset data) that can't be one and would just waste the
 * scan's time re-testing a regex against megabytes of unrelated text. */
const MAX_CANDIDATE_LENGTH = 200;

export function highestIdSuffix(value: unknown): number {
  let max = 0;

  const visit = (node: unknown): void => {
    if (typeof node === "string") {
      if (node.length > MAX_CANDIDATE_LENGTH) return;
      const match = ID_SUFFIX.exec(node);
      if (!match) return;
      const n = Number(match[1]);
      if (Number.isFinite(n) && n > max) max = n;
      return;
    }
    if (Array.isArray(node)) {
      for (const item of node) visit(item);
      return;
    }
    if (node !== null && typeof node === "object") {
      for (const key of Object.keys(node as Record<string, unknown>)) {
        visit((node as Record<string, unknown>)[key]);
      }
    }
  };

  visit(value);
  return max;
}
